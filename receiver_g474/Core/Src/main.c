void Update_Motors(uint8_t left_val, uint8_t right_val)
{
    uint32_t duty_l = 0;
    uint32_t duty_r = 0;
    // --- ЛЕВЫЙ МОТОР (TIM3 Канал 1 и Канал 2) ---
    if (left_val > 100) // Едем вперед (101..200)
    {
        duty_l = (uint32_t)(left_val - 100) * 8499 / 100;
        __HAL_TIM_SET_COMPARE(&htim3, TIM_CHANNEL_1, duty_l); // Задаем Ш�?М на вперед
        __HAL_TIM_SET_COMPARE(&htim3, TIM_CHANNEL_2, 0);      // Назад выключаем в 0
    }
    else if (left_val < 100) // Едем назад (0..99)
    {
        duty_l = (uint32_t)(100 - left_val) * 8499 / 100;
        __HAL_TIM_SET_COMPARE(&htim3, TIM_CHANNEL_1, 0);      // Вперед выключаем в 0
        __HAL_TIM_SET_COMPARE(&htim3, TIM_CHANNEL_2, duty_l); // Задаем Ш�?М на назад
    }
    else // Стоим на месте (ровно 100)
    {
        __HAL_TIM_SET_COMPARE(&htim3, TIM_CHANNEL_1, 0);
        __HAL_TIM_SET_COMPARE(&htim3, TIM_CHANNEL_2, 0);
    }
    // --- ПРАВЫЙ МОТОР (TIM3 Канал 3 и Канал 4) ---
    if (right_val > 100) // Едем вперед
    {
        duty_r = (uint32_t)(right_val - 100) * 8499 / 100;
        __HAL_TIM_SET_COMPARE(&htim3, TIM_CHANNEL_3, duty_r);
        __HAL_TIM_SET_COMPARE(&htim3, TIM_CHANNEL_4, 0);
    }
    else if (right_val < 100) // Едем назад
    {
        duty_r = (uint32_t)(100 - right_val) * 8499 / 100;
        __HAL_TIM_SET_COMPARE(&htim3, TIM_CHANNEL_3, 0);
        __HAL_TIM_SET_COMPARE(&htim3, TIM_CHANNEL_4, duty_r);
    }
    else // Стоим
    {
        __HAL_TIM_SET_COMPARE(&htim3, TIM_CHANNEL_3, 0);
        __HAL_TIM_SET_COMPARE(&htim3, TIM_CHANNEL_4, 0);
    }
}
