/* USER CODE BEGIN 4 */
void HAL_UART_RxCpltCallback(UART_HandleTypeDef *huart)
{
    if (huart->Instance == USART1)
    {
        switch (rx_state)
        {
            case STATE_IDLE:
                if (rx_byte == 0xAA) // Поймали стартовый байт пакета!
                {
                    rx_state = STATE_GET_L;
                }
                break;
            case STATE_GET_L:
                motor_l_cmd = rx_byte; // Запоминаем скорость левого колеса
                rx_state = STATE_GET_R;
                break;
            case STATE_GET_R:
                motor_r_cmd = rx_byte; // Запоминаем скорость правого колеса
                rx_state = STATE_GET_CRC;
                break;
            case STATE_GET_CRC:
                rx_crc = rx_byte; // Получили контрольную сумму

                // Проверяем: сошлась ли математика пакета?
                if (rx_crc == (motor_l_cmd ^ motor_r_cmd ^ 0xAA))
                {
                    // Если всё верно — обновляем скорость моторов!
                    Update_Motors(motor_l_cmd, motor_r_cmd);
                }

                rx_state = STATE_IDLE; // Возвращаемся в ожидание нового пакета
                break;
        }
        // Перезапускаем прерывание на прием следующего 1 байта
        HAL_UART_Receive_IT(&huart1, (uint8_t*)&rx_byte, 1);
    }
}
