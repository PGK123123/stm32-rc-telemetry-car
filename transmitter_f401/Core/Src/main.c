/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_DMA_Init();
  MX_ADC1_Init();
  MX_USART1_UART_Init();
  /* USER CODE BEGIN 2 */
  HAL_ADC_Start_DMA(&hadc1, (uint32_t*)adc_val, 2);
  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
	  // Центр джойстика по умолчанию выдает ~2048 (диапазон 0..4095)
	        // Переводим сырые значения АЦП в диапазон от -100 до +100
	        int32_t speed = ((int32_t)adc_val[1] - 2048) * 100 / 2048; // Вперед/назад (ось Y)
	        int32_t steer = ((int32_t)adc_val[0] - 2048) * 100 / 2048; // Влево/вправо (ось X)
	        // Математика дифференциального (танкового) руления
	        int32_t left = speed + steer;
	        int32_t right = speed - steer;
	        // Ограничиваем значения в пределах -100..+100
	        if (left > 100) left = 100;
	        if (left < -100) left = -100;
	        if (right > 100) right = 100;
	        if (right < -100) right = -100;
	        // Переводим в беззнаковый вид 0..200 для отправки (100 - это стоп)
	        uint8_t left_cmd = (uint8_t)(left + 100);
	        uint8_t right_cmd = (uint8_t)(right + 100);
	        // Собираем пакет для отправки по воздуху
	        tx_packet[0] = 0x55; // Преамбула (1-й байт "разогрева" приемника)
	        tx_packet[1] = 0x55; // Преамбула (2-й байт)
	        tx_packet[2] = 0x55; // Преамбула (3-й байт)
	        tx_packet[3] = 0x55; // Преамбула (4-й байт)
	        tx_packet[4] = 0xAA; // Стартовый байт начала данных
	        tx_packet[5] = left_cmd;  // Скорость левого колеса
	        tx_packet[6] = right_cmd; // Скорость правого колеса
	        tx_packet[7] = left_cmd ^ right_cmd ^ 0xAA; // Контрольная сумма (XOR)
	        // Отправляем пакет 8 байт через передатчик FS1000A
	        HAL_UART_Transmit(&huart1, tx_packet, 8, 100);
	        HAL_Delay(50); // Отправляем команды каждые 50 миллисекунд

    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
  }
  /* USER CODE END 3 */
}

